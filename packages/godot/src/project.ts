export interface ProjectGodotOptions {
  title: string;
  assembly: string;
  mainScene: string;
  width?: number;
  height?: number;
  icon?: string;
}

/** project.godot: application, autoloads, input map, Jolt physics and a realistic rendering setup. */
export function projectGodot(o: ProjectGodotOptions): string {
  const lines = [
    '; Engine configuration file.',
    '; Generated by AIGE (godot_export). Re-exporting rewrites it; change settings in project.json instead.',
    '',
    'config_version=5',
    '',
    '[application]',
    '',
    `config/name=${str(o.title)}`,
    `run/main_scene=${str(o.mainScene)}`,
    `config/features=PackedStringArray(${str(GODOT_FEATURES)}, "C#", "Forward Plus")`,
    ...(o.icon ? [`config/icon=${str(o.icon)}`] : []),
    '',
    '[autoload]',
    '',
    ...AUTOLOADS.map(([n, p]) => `${n}=${str(`*${p}`)}`),
    '',
    '[display]',
    '',
    `window/size/viewport_width=${o.width ?? 1920}`,
    `window/size/viewport_height=${o.height ?? 1080}`,
    'window/size/mode=2',
    'window/vsync/vsync_mode=1',
    '',
    '[dotnet]',
    '',
    `project/assembly_name=${str(o.assembly)}`,
    '',
    '[input]',
    '',
  ];
  for (const [action, events] of Object.entries(INPUT_ACTIONS)) {
    lines.push(`${action}={`, '"deadzone": 0.2,', `"events": [${events.join(', ')}]`, '}');
  }
  lines.push(
    '',
    '[physics]',
    '',
    '3d/physics_engine="Jolt Physics"',
    'common/physics_ticks_per_second=60',
    '',
    '[rendering]',
    '',
    'textures/default_filters/anisotropic_filtering_level=4',
    'anti_aliasing/quality/msaa_3d=2',
    'anti_aliasing/quality/use_taa=true',
    'lights_and_shadows/directional_shadow/size=8192',
    'lights_and_shadows/directional_shadow/soft_shadow_filter_quality=4',
    'lights_and_shadows/positional_shadow/soft_shadow_filter_quality=4',
    'lights_and_shadows/positional_shadow/atlas_size=8192',
    'environment/ssao/quality=3',
    'environment/ssil/quality=2',
    'environment/volumetric_fog/volume_size=128',
    'environment/volumetric_fog/volume_depth=128',
    'global_illumination/sdfgi/probe_ray_count=2',
    'environment/defaults/default_clear_color=Color(0, 0, 0, 1)',
    '',
  );
  return lines.join('\n');
}

