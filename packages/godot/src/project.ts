const res = (p: string) => (p.startsWith('res://') ? p : `res://${p}`);

/** A MaterialDoc as a Godot material (.tres). Packed AO/roughness/metal maps use ORMMaterial3D. */
export function materialTres(doc: MaterialDoc): string {
  const w = new TscnWriter();
  const tex = (p: string | undefined) =>
    p ? new Raw(`ExtResource(${str(w.ext('Texture2D', res(p)))})`) : undefined;
  const orm = tex(doc.ormMap);
  const [ru, rv] = doc.mapRepeat ?? [1, 1];
  const props = {
    transparency: doc.opacity < 1 ? 1 : undefined,
    cull_mode: doc.doubleSided ? 2 : undefined,
    vertex_color_use_as_albedo: doc.vertexColors ? true : undefined,
    albedo_color: color(doc.color, doc.opacity),
    albedo_texture: tex(doc.map),
    orm_texture: orm,
    roughness: doc.roughness,
    metallic: doc.metalness,
    emission_enabled: doc.emissive !== '#000000' ? true : undefined,
    emission: doc.emissive !== '#000000' ? color(doc.emissive) : undefined,
    emission_energy_multiplier: doc.emissive !== '#000000' ? doc.emissiveIntensity : undefined,
    normal_enabled: doc.normalMap ? true : undefined,
    normal_scale: doc.normalMap ? doc.normalScale : undefined,
    normal_texture: tex(doc.normalMap),
    ao_light_affect: orm ? 0.2 * doc.aoIntensity : undefined,
    uv1_scale: ru !== 1 || rv !== 1 ? vec3([ru, rv, 1]) : undefined,
  };
  return w.resource(orm ? 'ORMMaterial3D' : 'StandardMaterial3D', props);
}
